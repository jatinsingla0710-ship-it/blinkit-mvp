function buildProducts(): Product[] {
  const products: Product[] = [];
  for (const store of stores) {
    catalogSeed.forEach((seed, index) => {
      const stockJitter = (index + store.id.length) % 5;
      let stock = Math.max(0, seed.stock - stockJitter * 2);
      if (store.id === 'store-saket' && seed.name === 'Chilgoza') {
        stock = 4;
      }
      if (store.id === 'store-saket' && seed.name === 'Festival Assortment') {
        stock = 0;
      }
      products.push(
        withB2bDefaults({
          ...seed,
          id: `${store.id}-${seed.categoryId}-${index}`,
          storeId: store.id,
          stock,
        }),
      );
    });
  }
  return products;
}

export const products: Product[] = buildProducts();
